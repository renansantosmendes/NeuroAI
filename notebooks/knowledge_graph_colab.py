def search_entity(extractor, query: str):
    """Busca entidades que contenham o termo."""
    G = extractor.graph
    query = query.lower()

    results = []
    for node in G.nodes():
        if query in node:
            data = G.nodes[node]
            results.append({
                "name": data.get("label", node),
                "type": data.get("type", "unknown"),
                "description": data.get("description", ""),
                "connections": G.degree(node)
            })

    if results:
        print(f"\n🔍 Resultados para '{query}':")
        for r in results:
            print(f"   • {r['name']} ({r['type']}) - {r['connections']} conexões")
            if r['description']:
                print(f"     {r['description']}")
    else:
        print(f"\n⚠️ Nenhuma entidade encontrada para '{query}'")

    return results

def get_entity_relations(extractor, entity_name: str):
    """Mostra todas as relações de uma entidade."""
    G = extractor.graph
    entity = entity_name.lower()

    if entity not in G:
        # Tenta busca parcial
        matches = [n for n in G.nodes() if entity in n]
        if matches:
            entity = matches[0]
        else:
            print(f"⚠️ Entidade '{entity_name}' não encontrada")
            return

    label = G.nodes[entity].get("label", entity)
    print(f"\n🔗 Relações de '{label}':")

    # Relações de saída
    out_edges = list(G.out_edges(entity, data=True))
    if out_edges:
        print(f"\n   ➡️ Relações de saída:")
        for _, target, data in out_edges:
            target_label = G.nodes[target].get("label", target)
            print(f"      {label} --[{data.get('relation', '')}]--> {target_label}")

    # Relações de entrada
    in_edges = list(G.in_edges(entity, data=True))
    if in_edges:
        print(f"\n   ⬅️ Relações de entrada:")
        for source, _, data in in_edges:
            source_label = G.nodes[source].get("label", source)
            print(f"      {source_label} --[{data.get('relation', '')}]--> {label}")

