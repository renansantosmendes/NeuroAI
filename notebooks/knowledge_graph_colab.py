# Análise de métricas do grafo
def analyze_graph(extractor):
    """Analisa métricas do knowledge graph."""
    G = extractor.graph

    if G.number_of_nodes() == 0:
        print("⚠️ Grafo vazio!")
        return

    print("\n" + "="*50)
    print("📊 ANÁLISE DO KNOWLEDGE GRAPH")
    print("="*50)

    # Métricas básicas
    print(f"\n📌 Métricas Básicas:")
    print(f"   • Nós: {G.number_of_nodes()}")
    print(f"   • Arestas: {G.number_of_edges()}")
    print(f"   • Densidade: {nx.density(G):.4f}")

    # Componentes
    if G.is_directed():
        n_components = nx.number_weakly_connected_components(G)
    else:
        n_components = nx.number_connected_components(G)
    print(f"   • Componentes conectados: {n_components}")

    # Centralidade
    print(f"\n⭐ Top 10 por Centralidade de Grau:")
    degree_cent = nx.degree_centrality(G)
    for node, cent in sorted(degree_cent.items(), key=lambda x: x[1], reverse=True)[:10]:
        label = G.nodes[node].get("label", node)
        print(f"   • {label}: {cent:.4f}")

    # PageRank
    print(f"\n🔥 Top 10 por PageRank:")
    pagerank = nx.pagerank(G)
    for node, pr in sorted(pagerank.items(), key=lambda x: x[1], reverse=True)[:10]:
        label = G.nodes[node].get("label", node)
        print(f"   • {label}: {pr:.4f}")

    # Relações mais frequentes
    print(f"\n🔗 Tipos de Relações mais Frequentes:")
    relations = [G.edges[e].get("relation", "") for e in G.edges()]
    relation_counts = {}
    for r in relations:
        relation_counts[r] = relation_counts.get(r, 0) + 1
    for rel, count in sorted(relation_counts.items(), key=lambda x: x[1], reverse=True)[:10]:
        print(f"   • {rel}: {count}")

